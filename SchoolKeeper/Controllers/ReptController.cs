    [ApiController]
    [Route("api/[controller]")]
    [Authorize]
    public class ReptController : BaseController<Rept, ReptDto>
    {
        private readonly IUserService _userService;
        private readonly IDataFilterService _dataFilterService;
        private readonly SchoolKeeperDbContext _context;

        public ReptController(
            IGenericRepository<Rept> repo,
            IUserService userService,
            IDataFilterService dataFilterService,
            SchoolKeeperDbContext context) 
            : base(repo)
        {
            _userService = userService;
            _dataFilterService = dataFilterService;
            _context = context;
        }

        public override async Task<ActionResult<ResponseWrapper<IEnumerable<ReptDto>>>> GetAll([FromQuery] int page = 1, [FromQuery] int pageSize = 50)
        {
            var user = await _userService.GetCurrentUserAsync(HttpContext);
            if (user == null) throw new UnauthorizedException();

            // Согласно матрице: Admin, Security, Teacher
            if (user.Role != UserRole.Admin && user.Role != UserRole.Security && user.Role != UserRole.Teacher)
            {
                throw new UnauthorizedException("You don't have access to reports.");
            }

            var query = _context.Reports
                .Include(r => r.School)
                .Include(r => r.Generator)
                .AsQueryable();

            // Filter by school (except Admin)
            if (user.Role != UserRole.Admin)
            {
                query = _dataFilterService.FilterBySchool(query, user.SchoolId);
            }

            if (page <= 0) page = 1;
            if (pageSize <= 0 || pageSize > 500) pageSize = 50;

            var items = await query
                .OrderByDescending(r => r.GeneratedOn)
                .Skip((page - 1) * pageSize)
                .Take(pageSize)
                .ToListAsync();

            var dtos = items.Select(MapToDto).ToList();
            var response = new ResponseWrapper<IEnumerable<ReptDto>>(200, dtos);
            return Ok(response);
        }

        [HttpPost]
        public override async Task<ActionResult<ResponseWrapper<ReptDto>>> Create([FromBody] ReptDto dto)
        {
            var user = await _userService.GetCurrentUserAsync(HttpContext);
            if (user == null) throw new UnauthorizedException();

            // Согласно матрице: Admin, Security, Teacher
            if (user.Role != UserRole.Admin && user.Role != UserRole.Security && user.Role != UserRole.Teacher)
            {
                throw new UnauthorizedException("You don't have permission to create reports.");
            }

            // Set generated by to current user
            dto.GeneratedBy = user.Id;

            // Non-admin users can only create reports for their school
            if (user.Role != UserRole.Admin && dto.SchoolId != user.SchoolId)
            {
                throw new BadRequestException("You can only create reports for your school.");
            }

            // Set generated on to current time if not provided
            if (dto.GeneratedOn == default)
            {
                dto.GeneratedOn = DateTime.UtcNow;
            }

            return await base.Create(dto);
        }

        [HttpPut("{id:int}")]
        public override async Task<ActionResult<ResponseWrapper<ReptDto>>> Update(int id, [FromBody] ReptDto dto)
        {
            var user = await _userService.GetCurrentUserAsync(HttpContext);
            if (user == null) throw new UnauthorizedException();

            // Согласно матрице: Admin, Security, Teacher
            if (user.Role != UserRole.Admin && user.Role != UserRole.Security && user.Role != UserRole.Teacher)
            {
                throw new UnauthorizedException("You don't have permission to update reports.");
            }

            var report = await Repo.GetByIdAsync(id);
            if (report == null) throw new NotFoundException();

            // Check school access
            if (user.Role != UserRole.Admin && report.SchoolId != user.SchoolId)
            {
                throw new UnauthorizedException("You don't have access to this report.");
            }

            return await base.Update(id, dto);
        }

